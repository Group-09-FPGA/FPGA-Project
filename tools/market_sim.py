#!/usr/bin/env python3
"""Lively market feed for the FPGA order book (Ethernet / MoldUDP64 / ITCH).

Unlike order_journey.py (one narrated order at a time), this sends a continuous,
random, realistic-looking market:

* The book is pre-loaded to an "intermediate state" (about 70% of the 2048
  order slots, nearly every hash set and nearly every price-level square used).
* Afterwards the best bid and ask move together as a fair price random-walks
  (calm, trending and volatile regimes, momentum and jumps). Aggressive flow
  executes orders at the touch, market makers re-quote, orders are cancelled,
  replaced and deleted, and a deep tail of resting orders churns.

Everything is generated by this script and sent as ordinary ITCH messages, so
the FPGA is unchanged. The local model keeps the book consistent (no crossed
book, no unknown or duplicate order IDs, no over-execution) because any bad
event would fail-stop the hardware book.

The board must be freshly reset/programmed: MoldUDP64 sequence starts at 1.
"""
import argparse
import math
import os
import random
import re
import socket
import struct
import sys
import threading
import time

try:
    import serial
except ImportError:
    serial = None

SESSION = b"SESSION001"
TIMESTAMP = b"\x00\x00\x00\x01\x23\x45"
LOCATE = 1
LEVELS = 8192
SETS = 1024
SLOTS = 2048
MAX_PER_PACKET = 28
FRAME = re.compile(
    r"\[BBO\]\s+B:([0-9A-Fa-f]{8})\s*\|\s*A:([0-9A-Fa-f]{8})\s*\|\s*V:([01])\s*\|\s*E:([0-9A-Fa-f]{2})"
    r"\s*\|\s*QB:([0-9A-Fa-f]{8})\s*\|\s*QA:([0-9A-Fa-f]{8})\s*\|\s*N:([0-9A-Fa-f]{3})"
)
SETTINGS = re.compile(r"BASE:([0-9A-Fa-f]{8}).*?TICK:([0-9A-Fa-f]{8})")


def hash_set(ref):
    """Mirror lob_core.hash_oid's XOR of 10-bit order-ID slices."""
    return ((ref & 0x3ff) ^ ((ref >> 10) & 0x3ff) ^ ((ref >> 20) & 0x3ff) ^
            ((ref >> 30) & 0x3ff) ^ ((ref >> 40) & 0x3ff) ^ ((ref >> 50) & 0x3ff) ^
            ((ref >> 60) & 0xf))


# ---------------------------------------------------------------- ITCH / Mold
def itch_message(event, price_of, match):
    kind, ref, side, qty, idx, new_ref = event
    price = price_of(idx)
    prefix = struct.pack(">BHH6sQ", ord(kind), LOCATE, 0, TIMESTAMP, ref)
    if kind in ("A", "F"):
        body = prefix + struct.pack(">BI8sI", ord(side), qty, b"LOBDEMO ", price)
        return body + b"DEMO" if kind == "F" else body
    if kind == "E":
        return prefix + struct.pack(">IQ", qty, match)
    if kind == "C":
        return prefix + struct.pack(">IQBI", qty, match, ord("Y"), price)
    if kind == "X":
        return prefix + struct.pack(">I", qty)
    if kind == "D":
        return prefix
    if kind == "U":
        return prefix + struct.pack(">QII", new_ref, qty, price)
    raise ValueError(kind)


def mold_packet(first_seq, bodies):
    packet = struct.pack(">10sQH", SESSION, first_seq, len(bodies))
    for body in bodies:
        packet += struct.pack(">H", len(body)) + body
    return packet


# ------------------------------------------------------------------ book model
class Book:
    def __init__(self):
        self.orders = {}                      # ref -> [side, idx, qty]
        self.levels = {"B": {}, "S": {}}      # side -> idx -> set(refs)
        self.set_count = [0] * SETS
        self.used = set()

    def best(self, side):
        levels = self.levels[side]
        if not levels:
            return None
        return max(levels) if side == "B" else min(levels)

    def add(self, ref, side, idx, qty):
        assert ref not in self.orders and 0 <= idx < LEVELS and qty > 0
        self.orders[ref] = [side, idx, qty]
        self.levels[side].setdefault(idx, set()).add(ref)
        self.set_count[hash_set(ref)] += 1
        self.used.add(ref)

    def remove(self, ref):
        side, idx, _ = self.orders.pop(ref)
        refs = self.levels[side][idx]
        refs.discard(ref)
        if not refs:
            del self.levels[side][idx]
        self.set_count[hash_set(ref)] -= 1

    def reduce(self, ref, qty):
        order = self.orders[ref]
        assert 0 < qty <= order[2]
        if qty == order[2]:
            self.remove(ref)
        else:
            order[2] -= qty

    def stats(self):
        squares = {idx // 8 for side in self.levels.values() for idx in side}
        return {
            "orders": len(self.orders),
            "slots_pct": 100.0 * len(self.orders) / SLOTS,
            "sets_pct": 100.0 * sum(1 for n in self.set_count if n) / SETS,
            "squares_pct": 100.0 * len(squares) / (LEVELS // 8),
            "max_per_set": max(self.set_count),
        }


# ------------------------------------------------------------------- simulator
class Market:
    CENTER = 4096          # price step the market oscillates around ($ base + 4096 ticks)
    RANGE = 260            # the fair price stays within +/- this many steps

    def __init__(self, seed=None):
        self.rng = random.Random(seed)
        self.book = Book()
        self.fair = float(self.CENTER) + self.rng.uniform(-40, 40)
        self.half = 1.2
        self.velocity = 0.0
        self.regime = "calm"
        self.regime_left = 0
        self.match = 1000

    # -- identifiers ---------------------------------------------------------
    def new_ref(self):
        """Random order ID whose hash set is one of the emptiest sets."""
        low = min(self.book.set_count)
        candidates = [s for s, n in enumerate(self.book.set_count) if n == low]
        target = self.rng.choice(candidates)
        while True:
            ref = self.rng.getrandbits(48) | (1 << 47)
            ref &= ~0x3ff
            ref |= target ^ hash_set(ref)
            if ref not in self.book.used and ref:
                return ref

    # -- sizes -----------------------------------------------------------------
    def near_qty(self):
        return self.rng.choice((100, 100, 100, 200, 200, 300, 400, 500, 700, 1000))

    def tail_qty(self):
        return self.rng.choice((300, 500, 800, 1000, 1500, 2000, 3000, 5000))

    # -- price process ---------------------------------------------------------
    def step_fair(self):
        rng = self.rng
        if self.regime_left <= 0:
            self.regime = rng.choices(("calm", "trend", "volatile"), (5, 3, 2))[0]
            self.regime_left = rng.randint(30, 160)
            self.trend = rng.choice((-1, 1)) * rng.uniform(0.15, 0.7)
        self.regime_left -= 1
        sigma = {"calm": 0.35, "trend": 0.6, "volatile": 1.7}[self.regime]
        drift = self.trend if self.regime == "trend" else 0.0
        pull = (self.CENTER - self.fair) * 0.004
        self.velocity = 0.82 * self.velocity + rng.gauss(drift, sigma) + pull
        if rng.random() < 0.012:
            self.velocity += rng.choice((-1, 1)) * rng.uniform(4, 11)
        self.fair += self.velocity * 0.6
        self.fair = max(self.CENTER - self.RANGE, min(self.CENTER + self.RANGE, self.fair))
        target_half = {"calm": 1.0, "trend": 1.5, "volatile": 2.4}[self.regime]
        self.half += (target_half - self.half) * 0.1 + rng.gauss(0, 0.12)
        self.half = max(0.55, min(3.4, self.half))

    # -- helpers -----------------------------------------------------------------
    def emit(self, events, kind, ref, side, qty, idx, new_ref=0):
        events.append((kind, ref, side, qty, idx, new_ref))

    def sweep(self, events, side, limit_idx, budget):
        """Aggressive orders execute against the touch until it passes limit_idx."""
        book, rng = self.book, self.rng
        while budget > 0:
            best = book.best(side)
            if best is None or (best >= limit_idx if side == "S" else best <= limit_idx):
                break
            ref = rng.choice(sorted(book.levels[side][best]))
            remaining = book.orders[ref][2]
            qty = remaining
            if remaining > 100 and rng.random() < 0.3:
                qty = rng.randrange(100, remaining, 100)
            kind = "C" if rng.random() < 0.25 else "E"
            self.emit(events, kind, ref, side, qty, best)
            book.reduce(ref, qty)
            budget -= 1
        return budget

    def add_order(self, events, side, idx, qty):
        book = self.book
        if not 0 <= idx < LEVELS or len(book.orders) >= 1850:
            return False
        opposite = book.best("S" if side == "B" else "B")
        if opposite is not None and (idx >= opposite if side == "B" else idx <= opposite):
            return False
        ref = self.new_ref()
        kind = "F" if self.rng.random() < 0.15 else "A"
        self.emit(events, kind, ref, side, qty, idx)
        book.add(ref, side, idx, qty)
        return True

    def band_refs(self, width):
        mid = int(self.fair)
        return [r for r, (_, i, _) in self.book.orders.items() if abs(i - mid) <= width]

    # -- one market tick ------------------------------------------------------------
    def tick(self):
        rng, book = self.rng, self.book
        events = []
        self.step_fair()
        bid_t = int(math.floor(self.fair - self.half))
        ask_t = int(math.ceil(self.fair + self.half))
        if ask_t <= bid_t:
            ask_t = bid_t + 1

        # 1. The touch follows the fair price: buyers lift offers / sellers hit bids.
        budget = 60
        budget = self.sweep(events, "S", ask_t, budget)
        budget = self.sweep(events, "B", bid_t, budget)

        # 2. Market makers re-quote around the new touch.
        best_bid, best_ask = book.best("B"), book.best("S")
        if best_bid is None or best_bid < bid_t - 1:
            self.add_order(events, "B", bid_t - rng.choice((0, 0, 1)), self.near_qty())
        if best_ask is None or best_ask > ask_t + 1:
            self.add_order(events, "S", ask_t + rng.choice((0, 0, 1)), self.near_qty())
        for _ in range(rng.choice((1, 2, 2, 3, 4))):
            side = rng.choice("BS")
            depth = int(rng.expovariate(0.32))
            idx = bid_t - depth if side == "B" else ask_t + depth
            self.add_order(events, side, idx, self.near_qty())

        # 3. Cancels, partial cancels and replaces near the touch.
        crowd = len(book.orders)
        cancel_p = 0.55 + (0.35 if crowd > 1650 else 0.0) - (0.35 if crowd < 1250 else 0.0)
        near = self.band_refs(45)
        if near and rng.random() < cancel_p:
            ref = rng.choice(near)
            qty = book.orders[ref][2]
            if rng.random() < 0.4 and qty > 100:
                cut = rng.randrange(100, qty, 100) if qty > 100 else qty
                self.emit(events, "X", ref, book.orders[ref][0], cut, book.orders[ref][1])
                book.reduce(ref, cut)
            else:
                side, idx, _ = book.orders[ref]
                self.emit(events, "D", ref, side, 0, idx)
                book.remove(ref)
        if near and rng.random() < 0.3:
            ref = rng.choice(near)
            if ref in book.orders:
                side, idx, qty = book.orders[ref]
                new_idx = idx + (rng.randint(1, 3) if side == "B" else -rng.randint(1, 3))
                opposite = book.best("S" if side == "B" else "B")
                ok = 0 <= new_idx < LEVELS and (
                    opposite is None or (new_idx < opposite if side == "B" else new_idx > opposite))
                if ok and len(book.orders) < 1850:
                    nref = self.new_ref()
                    self.emit(events, "U", ref, side, qty, new_idx, nref)
                    book.remove(ref)
                    book.add(nref, side, new_idx, qty)

        # 4. Deep tail: keep a resting order in nearly every price-level square.
        if rng.random() < 0.5:
            self.refresh_tail(events)

        # 5. Occasional large aggressive order walks through several levels.
        if rng.random() < 0.02:
            if rng.random() < 0.5:
                self.sweep(events, "S", ask_t + rng.randint(2, 5), 30)
            else:
                self.sweep(events, "B", bid_t - rng.randint(2, 5), 30)
        return events

    def refresh_tail(self, events):
        book, rng = self.book, self.rng
        if len(book.orders) >= 1850:
            return
        covered = {idx // 8 for side in book.levels.values() for idx in side}
        mid = int(self.fair)
        for _ in range(6):
            bucket = rng.randrange(LEVELS // 8)
            if bucket in covered:
                continue
            idx = bucket * 8 + rng.randrange(8)
            if abs(idx - mid) <= 4:
                continue
            self.add_order(events, "B" if idx < mid else "S", idx, self.tail_qty())
            return

    # -- initial intermediate book -------------------------------------------------
    def preload(self, target=1450):
        rng, book = self.rng, self.book
        events = []
        mid = int(self.fair)
        bid0, ask0 = mid - 1, mid + 1
        # Dense ladder near the touch, outward from the best prices.
        for depth in range(0, 90):
            count = 1 + int(rng.random() * 8.0 * math.exp(-depth / 26.0) + 0.5)
            for _ in range(count):
                self.add_order(events, "B", bid0 - depth, self.near_qty())
                self.add_order(events, "S", ask0 + depth, self.near_qty())
        # One resting order in almost every price-level square across the range.
        buckets = list(range(LEVELS // 8))
        rng.shuffle(buckets)
        for bucket in buckets:
            if len(book.orders) >= target:
                break
            if rng.random() < 0.04:
                continue
            idx = bucket * 8 + rng.randrange(8)
            if bid0 - 90 < idx < ask0 + 90:
                continue
            self.add_order(events, "B" if idx < mid else "S", idx, self.tail_qty())
        # Top up with mid-depth orders until the requested size is reached.
        while len(book.orders) < target:
            idx = mid + rng.choice((-1, 1)) * rng.randint(30, 700)
            self.add_order(events, "B" if idx < mid else "S", idx, self.tail_qty())
        return events


# ------------------------------------------------------------------- board link
class Board:
    """Reads the UART [BBO] line in a background thread."""

    def __init__(self, port):
        self.frame = None
        self.stamp = 0.0
        self.base = None
        self.tick = None
        self.bad = None
        self.stop = False
        if port and serial is None:
            sys.exit("pyserial is required for UART monitoring (pip install pyserial)")
        self.port = serial.Serial(port, 115200, timeout=0.2) if port else None
        if self.port:
            threading.Thread(target=self.run, daemon=True).start()

    def run(self):
        buffer = ""
        while not self.stop:
            try:
                data = self.port.read(256).decode("ascii", "ignore")
            except Exception:
                return
            buffer += data
            while "\n" in buffer:
                line, buffer = buffer.split("\n", 1)
                match = FRAME.search(line)
                if not match:
                    continue
                setting = SETTINGS.search(line)
                if setting:
                    self.base, self.tick = int(setting.group(1), 16), int(setting.group(2), 16)
                bid, ask, valid, error, _, _, count = match.groups()
                self.frame = dict(bid=int(bid, 16), ask=int(ask, 16), valid=valid == "1",
                                  error=int(error, 16), active=int(count, 16))
                self.stamp = time.time()
                if not self.frame["valid"] or self.frame["error"]:
                    self.bad = dict(self.frame)

    def wait_frame(self, newer_than, timeout=3.0):
        end = time.time() + timeout
        while time.time() < end:
            if self.stamp > newer_than:
                return self.frame
            time.sleep(0.05)
        return None


# ------------------------------------------------------------------------ main
def money(price):
    return f"${price / 10000:,.2f}"


def main():
    parser = argparse.ArgumentParser(description="Realistic random market feed for the FPGA order book")
    parser.add_argument("--target-ip", default="192.168.1.255", help="broadcast address of the board-facing link")
    parser.add_argument("--port", type=int, default=10443)
    parser.add_argument("--uart-port", default="/dev/ttyUSB1" if os.path.exists("/dev/ttyUSB1") else None,
                        help="board UART for confirmation (default /dev/ttyUSB1 if present)")
    parser.add_argument("--rate", type=float, default=10.0, help="market ticks per second (default 10)")
    parser.add_argument("--orders", type=int, default=1450, help="orders in the pre-loaded book")
    parser.add_argument("--preload-delay", type=float, default=0.04, help="seconds between pre-load packets")
    parser.add_argument("--seed", type=int, default=None)
    parser.add_argument("--duration", type=float, default=0, help="seconds to run (0 = until Ctrl+C)")
    parser.add_argument("--check-every", type=float, default=30.0,
                        help="seconds between pauses that compare the local book with the board (0 = never)")
    parser.add_argument("--dry-run", action="store_true", help="simulate and validate without sending")
    parser.add_argument("--no-board-check", action="store_true", help="do not require an empty valid book at start")
    args = parser.parse_args()

    market = Market(args.seed)
    book = market.book
    board = Board(None if args.dry_run else args.uart_port)
    base, tick = 900000, 1000

    if board.port:
        print("Waiting for the board's UART line ...")
        frame = board.wait_frame(0, 5)
        if not frame:
            sys.exit("No [BBO] line from the board. Check --uart-port and that the FPGA is programmed.")
        if board.base:
            base, tick = board.base, board.tick
        if not args.no_board_check and (not frame["valid"] or frame["active"] or frame["error"]):
            sys.exit("Board book is not empty/valid. Reprogram the FPGA (or press CPU RESET) and run again.")
    price_of = lambda idx: base + idx * tick

    sock = None
    if not args.dry_run:
        sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        sock.setsockopt(socket.SOL_SOCKET, socket.SO_BROADCAST, 1)

    state = {"seq": 1, "sent": 0, "packets": 0, "match": 1000}

    def send(events, delay=0.0):
        for start in range(0, len(events), MAX_PER_PACKET):
            chunk = events[start:start + MAX_PER_PACKET]
            bodies = []
            for event in chunk:
                state["match"] += 1
                bodies.append(itch_message(event, price_of, state["match"]))
            if sock:
                sock.sendto(mold_packet(state["seq"], bodies), (args.target_ip, args.port))
            state["seq"] += len(chunk)
            state["sent"] += len(chunk)
            state["packets"] += 1
            if delay:
                time.sleep(delay)

    def report(prefix=""):
        bid, ask = book.best("B"), book.best("S")
        quote = f"bid {money(price_of(bid))}  ask {money(price_of(ask))}" if bid is not None and ask is not None else "no quote"
        extra = ""
        if board.frame:
            extra = f"  | board: bid {money(board.frame['bid'])} ask {money(board.frame['ask'])} orders {board.frame['active']}"
        print(f"{prefix}{state['sent']:>7} msgs  {len(book.orders):>5} orders  {quote}  regime {market.regime:<8}{extra}")

    def verify(label):
        """Pause, then compare the local book with the board."""
        if not board.port:
            return True
        time.sleep(0.4)
        stamp = time.time()
        frame = board.wait_frame(stamp, 3.0)
        if not frame:
            print(f"{label}: no UART update to compare")
            return True
        bid, ask = book.best("B"), book.best("S")
        want = (price_of(bid), price_of(ask), len(book.orders))
        got = (frame["bid"], frame["ask"], frame["active"])
        ok = want == got and frame["valid"] and not frame["error"]
        print(f"{label}: board {'MATCHES' if ok else 'DIFFERS FROM'} local book "
              f"(local bid {money(want[0])} ask {money(want[1])} orders {want[2]}; "
              f"board bid {money(got[0])} ask {money(got[1])} orders {got[2]})")
        return ok

    # ---- pre-load an intermediate book -------------------------------------------
    events = market.preload(args.orders)
    stats = book.stats()
    print(f"Pre-loading {len(events)} orders: {stats['slots_pct']:.0f}% of order slots, "
          f"{stats['sets_pct']:.0f}% of hash sets, {stats['squares_pct']:.0f}% of price-level squares "
          f"(max {stats['max_per_set']} per set)")
    send(events, 0 if args.dry_run else args.preload_delay)
    if board.port:
        time.sleep(1.5)
        verify("After pre-load")

    # ---- live market --------------------------------------------------------------
    print("Live market running. Ctrl+C to stop.")
    start = last_report = last_check = time.time()
    interval = 1.0 / max(args.rate, 0.1)
    try:
        while True:
            now = time.time()
            if args.duration and now - start >= args.duration:
                break
            events = market.tick()
            if events:
                send(events)
            if args.dry_run:
                bid, ask = book.best("B"), book.best("S")
                assert bid is not None and ask is not None and bid < ask, "crossed book"
                assert len(book.orders) <= SLOTS
            if board.bad:
                print(f"BOARD REPORTED A PROBLEM: {board.bad}. Stopping the feed.")
                break
            if now - last_report >= 2.0:
                report()
                last_report = now
            if args.check_every and board.port and now - last_check >= args.check_every:
                verify("Sync check")
                last_check = time.time()
            wait = interval * market.rng.uniform(0.3, 1.8)
            if market.rng.random() < 0.04:
                wait *= 0.1           # burst
            elif market.rng.random() < 0.03:
                wait *= 3.0           # lull
            time.sleep(0 if args.dry_run else wait)
    except KeyboardInterrupt:
        print()
    board.stop = True
    report("Final: ")
    stats = book.stats()
    print(f"Book: {stats['slots_pct']:.0f}% slots, {stats['sets_pct']:.0f}% hash sets, "
          f"{stats['squares_pct']:.0f}% price squares, {state['packets']} packets, {state['sent']} messages")


if __name__ == "__main__":
    main()
